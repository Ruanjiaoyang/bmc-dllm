"""
Unified dataset base class for multi-task evaluation.
Defines the interface and helpers shared by all tasks.
"""
import torch
from abc import ABC, abstractmethod
from typing import Dict, Any, Tuple, Optional


class BaseReasoningDataset(torch.utils.data.Dataset, ABC):
    """
    Common base class for reasoning-task datasets.

    Subclasses must implement:
    1. load_test_dataset() - load the test data
    2. extract_answer() - extract the answer from generated text
    3. check_correctness() - verify answer correctness
    4. load_few_shot_examples() - load few-shot examples (optional)
    """

    # Task name (must be set by subclasses)
    TASK_NAME = "base"
    
    def __init__(
        self,
        tokenizer,
        num_examples: int = 0,
        add_reasoning: bool = True,
        system_prompt: str = "",
        subsample: int = -1,
    ):
        """
        Args:
            tokenizer: HuggingFace tokenizer
            num_examples: number of few-shot examples
            add_reasoning: whether to append the <reasoning> tag
            system_prompt: system prompt for the task
            subsample: number of samples to evaluate (-1 means all)
        """
        self.tokenizer = tokenizer
        self.num_examples = num_examples
        self.add_reasoning = add_reasoning
        self.system_prompt = system_prompt
        
        # 1. Load the dataset
        self.load_test_dataset()
        
        # 2. Build the few-shot prompt
        self.create_few_shot_prompt()
        
        # 3. Subsample
        import numpy as np
        
        # Clamp subsample to the dataset size so np.random.choice cannot fail
        if subsample != -1:
            if subsample > len(self.dataset):
                print(f"[WARN] subsample ({subsample}) > dataset size ({len(self.dataset)})")
                print(f"   Adjusting subsample to {len(self.dataset)}")
                subsample = len(self.dataset)
            
            self.subsample = np.random.choice(
                len(self.dataset), 
                subsample, 
                replace=False
            )
        else:
            self.subsample = np.arange(len(self.dataset))
        
        print(f"[{self.TASK_NAME}] Evaluating {len(self.subsample)} examples")
    
    def __len__(self):
        return len(self.subsample)
    
    @abstractmethod
    def load_test_dataset(self):
        """Load the test dataset - must be implemented by subclasses."""
        pass
    
    @abstractmethod
    def extract_answer(self, text: str) -> Optional[str]:
        """
        Extract the answer from generated text.
        
        Args:
            text: text generated by the model
            
        Returns:
            The extracted answer as a string, or None if extraction fails.
        """
        pass
    
    @abstractmethod
    def check_correctness(
        self, 
        generated_answer: Any, 
        ground_truth: Any,
        question: Optional[str] = None
    ) -> bool:
        """
        Check whether the generated answer is correct.
        
        Args:
            generated_answer: answer extracted from the generated text
            ground_truth: reference answer
            question: the original question (required by some tasks)
            
        Returns:
            True if the answer is correct.
        """
        pass
    
    def create_prompt(self, input_text: str) -> str:
        """Build the full input prompt."""
        if self.num_examples > 0:
            prompt = f"{self.few_shot_prompt}\n\nQuestion: {input_text}\nAnswer:\n"
        else:
            prompt = input_text
        
        messages = [{
            "role": "user", 
            "content": self.system_prompt + "\n\n" + prompt
        }]
        
        user_input = self.tokenizer.apply_chat_template(
            messages, 
            add_generation_prompt=True, 
            tokenize=False
        )
        
        if self.add_reasoning:
            return user_input + "<reasoning>"
        else:
            return user_input
    
    def load_few_shot_examples(self):
        """
        Load few-shot examples - subclasses may override.
        
        Returns:
            List of examples with 'question' and 'answer' keys
        """
        return []
    
    def create_few_shot_prompt(self):
        """Build the few-shot prompt."""
        few_shot_examples = self.load_few_shot_examples()
        
        formatted_examples = []
        for example in few_shot_examples:
            input_text = example["question"]
            answer = example["answer"]
            formatted_examples.append(f"Question: {input_text}\nAnswer:\n{answer}")
        
        self.few_shot_prompt = "\n\n".join(formatted_examples)
    
    @abstractmethod
    def __getitem__(self, idx) -> Tuple[str, str, Any]:
        """
        Get a data sample.
        
        Returns:
            (prompt, question, answer)
        """
        pass
    
    def collate_fn(self, batch):
        """Generic collate function."""
        prompts = [item[0] for item in batch]
        questions = [item[1] for item in batch]
        answers = [item[2] for item in batch]
        
        input_ids = self.tokenizer(
            prompts, 
            padding_side="left", 
            return_tensors="pt", 
            padding="longest"
        ).input_ids
        
        return {
            "input_ids": input_ids, 
            "questions": questions, 
            "answers": answers, 
            "prompts": prompts
        }
    
    def get_metrics_info(self) -> Dict[str, Any]:
        """
        Return task-specific evaluation information.
        
        Returns:
            A dict with task metadata.
        """
        return {
            "task_name": self.TASK_NAME,
            "num_examples": self.num_examples,
            "total_samples": len(self.subsample),
        }